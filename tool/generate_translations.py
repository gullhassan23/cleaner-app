def main():
    with open(ROOT / "app_en.arb", encoding="utf-8") as f:
        en = json.load(f)
    for loc in ("ur", "zh", "ar", "es"):
        out = {"@@locale": loc}
        for k, v in en.items():
            if k.startswith("@@"):
                continue
            if k.startswith("@"):
                out[k] = v
            elif k in T:
                out[k] = T[k][loc]
            else:
                out[k] = v  # fallback
        path = ROOT / f"app_{loc}.arb"
        with open(path, "w", encoding="utf-8") as f:
            json.dump(out, f, ensure_ascii=False, indent=2)
            f.write("\n")
        missing = [k for k in en if not k.startswith("@") and k not in T]
        print(f"{loc}: {len(missing)} keys using English fallback")

if __name__ == "__main__":
    main()
